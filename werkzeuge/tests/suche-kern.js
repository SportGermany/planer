t('ex 3 klein', ref('ex 3'), null);
t('ex 3,14 mit Vers', ref('ex 3,14'), '2. Mose 3,14');
t('ps 23 klein', ref('ps 23'), 'Psalm 23');
t('Bereich gekappt', ref('Ps 23,1-99'), 'Psalm 23,1–6');
